import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {parse} from 'yaml';
export const root=resolve(import.meta.dirname,'../..');
export const hash=x=>createHash('sha256').update(x).digest('hex');
export function migrationSeed(snapshot=JSON.parse(readFileSync(resolve(root,'content/emdash/snapshot.json')))){
  assert.equal(snapshot.mode,'pinned-migration-seed');
  const content={posts:[],authors:[]},mapping=[],seen=new Set();
  for(const d of snapshot.documents){
    assert.match(d.path,/^src\/content\/docs\/[a-z0-9/_-]+\.md$/);
    assert.ok(!d.path.split('/').includes('..')&&!seen.has(d.applicationId));seen.add(d.applicationId);
    const bytes=readFileSync(resolve(root,d.path));assert.equal(hash(bytes),d.bodySha256,'Migration source changed');
    const text=bytes.toString('utf8'),fm=text.match(/^---\s*\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);assert.ok(fm);
    const data=parse(fm[1],{uniqueKeys:true});assert.deepEqual(data,d.item.data);
    assert.equal(data.status,'published');assert.equal(data.draft,false);
    const collection=data.contentKind==='author'?'authors':'posts',slug=d.path.split('/').at(-1).replace(/\.md$/,'');
    const {title,summary,...metadata}=data,body=text.slice(fm[0].length);
    content[collection].push({id:d.applicationId,slug,status:'published',locale:data.language??'id',data:{application_id:d.applicationId,title,summary:summary??'',body,metadata}});
    mapping.push({applicationId:d.applicationId,collection,slug,originalPath:d.path,sourceSha256:d.bodySha256,bodySha256:hash(body)});
  }
  const fields=[{slug:'title',label:'Title',type:'string',required:true,searchable:true},{slug:'summary',label:'Summary',type:'text'},{slug:'body',label:'Markdown body',type:'text',required:true},{slug:'application_id',label:'Application identity',type:'string',required:true,unique:true},{slug:'metadata',label:'Editorial metadata, dates, taxonomy and author references',type:'json',required:true}];
  return {seed:{version:'1',defaultLocale:'id',meta:{name:'Preserved publication content',description:'One-time import of the eight admitted editorial records. EmDash owns subsequent edits.'},collections:[{slug:'posts',label:'Articles'},{slug:'authors',label:'Authors'}].map(c=>({...c,routable:false,supports:['drafts','revisions'],fields})),content},mapping};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const {seed,mapping}=migrationSeed();mkdirSync(resolve(root,'cms/migration'),{recursive:true});
 writeFileSync(resolve(root,'cms/migration/seed.json'),JSON.stringify(seed,null,2)+'\n');
 writeFileSync(resolve(root,'cms/migration/source-map.json'),JSON.stringify(mapping,null,2)+'\n');
 console.log(JSON.stringify({status:'PASS',admittedRecords:mapping.length,counts:Object.fromEntries(Object.entries(seed.content).map(([n,v])=>[n,v.length])),providerIds:'Generated by EmDash; seed-local IDs are application references only'}));
}
